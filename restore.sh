#!/usr/bin/env bash
# Restores into NEW volumes. The previous volumes are never overwritten or deleted.
set -Eeuo pipefail
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)/docker/lib.sh"
require_docker
command -v openssl >/dev/null || die 'openssl is required for new restore volume names.'
umask 0077
[[ $# -eq 1 ]] || die 'Usage: bash restore.sh /absolute/path/to/completed-backup'
snapshot="$(cd -- "$1" && pwd -P)"
for file in database.sql.gz files.tar deployment.env manifest.json integrity.txt SHA256SUMS; do
    [[ -f "$snapshot/$file" ]] || die "Incomplete backup: $file is missing."
done
# Only the files generated by our backup format are accepted in the checksum list.
expected='database.sql.gz files.tar deployment.env manifest.json integrity.txt'
for file in $expected; do
    [[ "$(awk -v name="$file" '$2 == name {n++} END {print n+0}' "$snapshot/SHA256SUMS")" == 1 ]] || die "Invalid checksum manifest for $file"
done
[[ "$(wc -l < "$snapshot/SHA256SUMS")" -eq 5 ]] || die 'Unexpected checksum manifest entries.'
(cd "$snapshot" && sha256sum --check --strict SHA256SUMS)
gzip -t "$snapshot/database.sql.gz"
tar -tf "$snapshot/files.tar" | awk '
    /^\// || /(^|\/)\.\.($|\/)/ { bad=1 }
    END { exit bad ? 1 : 0 }
' || die 'Unsafe archive paths.'
tar -tvf "$snapshot/files.tar" | awk 'substr($0,1,1) != "-" && substr($0,1,1) != "d" { bad=1 } END { exit bad ? 1 : 0 }' || die 'Archive contains unsupported links/special files.'

current_port="${APP_PORT:-8085}"
current_url="${APP_URL:-http://localhost:$current_port}"
current_backups="${BACKUP_DIR:-$(dirname -- "$snapshot")}"
if [[ -f "$FILEVAULT_ENV_FILE" ]]; then
    load_config
    current_port="$APP_PORT"; current_url="$APP_URL"; current_backups="$BACKUP_DIR"
    # A usable current deployment gets a safety backup before any service is stopped.
    if [[ -n "$(compose ps --status running -q app)" ]]; then
        compose run --rm --no-deps --entrypoint /usr/local/bin/filevault-backup backup
    fi
    compose stop --timeout 300 backup app db
    previous="$FILEVAULT_ENV_FILE.pre-restore.$(date -u +%Y%m%dT%H%M%SZ)"
    cp "$FILEVAULT_ENV_FILE" "$previous"; chmod 0600 "$previous"
    echo "Previous deployment config retained at $previous; its original volumes will remain untouched."
fi

cp "$snapshot/deployment.env" "$FILEVAULT_ENV_FILE"
chmod 0600 "$FILEVAULT_ENV_FILE"
suffix="$(date -u +%Y%m%d%H%M%S)-$(openssl rand -hex 4)"
write_value "$FILEVAULT_ENV_FILE" DB_VOLUME "filevault_database_restore_$suffix"
write_value "$FILEVAULT_ENV_FILE" FILES_VOLUME "filevault_uploads_restore_$suffix"
write_value "$FILEVAULT_ENV_FILE" RUNTIME_VOLUME "filevault_runtime_restore_$suffix"
write_value "$FILEVAULT_ENV_FILE" APP_PORT "$current_port"
write_value "$FILEVAULT_ENV_FILE" APP_URL "$current_url"
write_value "$FILEVAULT_ENV_FILE" BACKUP_DIR "$current_backups"
mkdir -p -- "$current_backups"
if [[ -f "$current_backups/.filevault-target-id" ]]; then
    target_id="$(cat "$current_backups/.filevault-target-id")"
    [[ "$target_id" =~ ^[a-f0-9]{32}$ ]] || die 'Invalid backup target marker.'
else
    target_id="$(openssl rand -hex 16)"
    printf '%s\n' "$target_id" > "$current_backups/.filevault-target-id"
fi
write_value "$FILEVAULT_ENV_FILE" BACKUP_TARGET_ID "$target_id"
write_value "$FILEVAULT_ENV_FILE" BACKUP_UID "$(id -u)"
write_value "$FILEVAULT_ENV_FILE" BACKUP_GID "$(id -g)"
write_value "$FILEVAULT_ENV_FILE" DATA_INITIALIZED true
load_config
mkdir -p -- "$BACKUP_DIR"
for volume in "$DB_VOLUME" "$FILES_VOLUME" "$RUNTIME_VOLUME"; do
    if docker volume inspect "$volume" >/dev/null 2>&1; then die "Restore target $volume unexpectedly exists. No data was imported."; fi
    create_volume "$volume"
done
compose config --quiet
compose build app
compose up -d --wait --wait-timeout 240 db
tables="$(compose exec -T db sh -c 'MYSQL_PWD="$MARIADB_PASSWORD" mariadb -u "$MARIADB_USER" "$MARIADB_DATABASE" -Nse "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = DATABASE()"')"
[[ "$tables" == 0 ]] || die 'Restore database is not empty. Refusing import.'
gzip -dc "$snapshot/database.sql.gz" | compose exec -T db sh -c 'MYSQL_PWD="$MARIADB_PASSWORD" exec mariadb -u "$MARIADB_USER" "$MARIADB_DATABASE"'
cat "$snapshot/files.tar" | compose run --rm -T --no-deps --entrypoint bash app -c '
    set -euo pipefail
    target=/var/www/html/storage/app/server-storage
    [[ -z "$(find "$target" -mindepth 1 -print -quit)" ]] || { echo "Restore uploads volume is not empty" >&2; exit 1; }
    tar --no-same-owner -C "$target" -xf -
    chown -R www-data:www-data "$target"
'
echo 'Verifying restored files against the restored database before opening the HTTP port...'
compose run --rm --no-deps --entrypoint php app artisan local-storage:verify --hashes
FILEVAULT_SKIP_PREDEPLOY_BACKUP=1 bash "$PROJECT_ROOT/start.sh"
echo 'Recovery completed into new volumes. Existing users retain their previous passwords.'
